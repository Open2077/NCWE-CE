using System.Globalization;
using System.Numerics;
using System.Text;
using NCWE.Core;
using NCWE.Formats.CustomSounds;

namespace NCWE.Export;

// The custom sounds of a project as Open77 plays them (package audio, op77.62+): the files go into
// the resource under sounds/, a generated client script starts the sounds near each player (Open77
// gives a resource 16 handles, so a world can hold more sounds than it plays at once), and synced
// loops run on the server, one timeline for every player.
public sealed record Open77SoundFile(string SourcePath, string PublishedPath, long Bytes);
public sealed record Open77SoundEmitter(string Name, Vector3 Position, string PublishedPath, SoundSettings Settings, float MaxDistance, double Duration);

public sealed record Open77SoundSet(IReadOnlyList<Open77SoundFile> Files, IReadOnlyList<Open77SoundEmitter> Emitters)
{
    public static readonly Open77SoundSet Empty = new([], []);
    public bool IsEmpty => Emitters.Count == 0;
    public int Synced => Emitters.Count(e => e.Settings.Synced);
}

public static class Open77Sounds
{
    public const string ClientScript = "client/ncwe_sounds.lua", ServerScript = "server/ncwe_sounds.lua";
    public const string Marker = "-- Generated by NCWE Studio";
    public const string BlockStart = "-- NCWE sounds: generated by NCWE Studio, rewritten by every export (edit them in the Studio)", BlockEnd = "-- end of NCWE sounds";
    // Sounds a client plays at once, nearest first (the rest of the 16 handles stay for synced loops).
    public const int MaxLocalActive = 12;

    // The project's custom sound elements, resolved against the library.
    public static Open77SoundSet Collect(ProjectData project, CustomSoundLibrary library)
    {
        var emitters = new List<Open77SoundEmitter>();
        var files = new Dictionary<string, Open77SoundFile>(StringComparer.OrdinalIgnoreCase);
        foreach (var element in project.Changes.Elements.Values.Where(e => e.Properties.Kind == ElementKind.CustomSound).OrderBy(e => e.Id, StringComparer.Ordinal))
        {
            var settings = element.Properties.Audio!;
            var info = library.Get(settings.Sound) ?? throw new InvalidDataException($"Sound \"{element.Name}\": its file ({settings.Sound}) is no longer in your custom sound library.");
            string source = library.FilePath(info);
            if (!File.Exists(source)) throw new InvalidDataException($"Sound \"{element.Name}\": {source} is missing.");
            files.TryAdd(info.PublishedPath, new(source, info.PublishedPath, new FileInfo(source).Length));
            emitters.Add(new(element.Name, element.Transform.Position, info.PublishedPath, settings, element.Properties.Radius, info.Duration));
        }
        var set = new Open77SoundSet(files.Values.OrderBy(f => f.PublishedPath, StringComparer.Ordinal).ToArray(), emitters);
        Validate(set);
        return set;
    }

    public static void Validate(Open77SoundSet set)
    {
        if (set.Synced > Open77Audio.HandlesPerResource)
            throw new InvalidDataException($"{set.Synced} sounds are synced between players: Open77 plays {Open77Audio.HandlesPerResource} at most per resource. Untick \"Synced\" on the ambient ones (they then start near each player).");
        foreach (var file in set.Files)
            if (file.Bytes > Open77Audio.MaxFileBytes) throw new InvalidDataException($"{file.PublishedPath} is larger than Open77's 16 MiB per sound.");
        foreach (var emitter in set.Emitters.Where(e => e.Settings.Synced))
            if (emitter.Duration is <= 0 or > Open77Audio.MaxDuration) throw new InvalidDataException($"Sound \"{emitter.Name}\": a synced loop needs a clip of 0 to 600 seconds.");
    }

    // The open77.lua lines that declare the sounds, between two markers (replaced as a whole).
    public static string ManifestBlock(Open77SoundSet set)
    {
        var block = new StringBuilder();
        block.Append(BlockStart).Append('\n');
        block.Append("files { ").Append(string.Join(", ", set.Files.Select(f => Quote(f.PublishedPath)))).Append(" }\n");
        block.Append("permissions { ").Append(set.Synced > 0 ? "\"audio.play\", \"audio.network\"" : "\"audio.play\"").Append(" }\n");
        if (set.Emitters.Any(e => !e.Settings.Synced)) block.Append("client_script ").Append(Quote(ClientScript)).Append('\n');
        if (set.Synced > 0) block.Append("server_script ").Append(Quote(ServerScript)).Append('\n');
        block.Append(BlockEnd).Append('\n');
        return block.ToString();
    }

    // The manifest without a previous sound block.
    public static string RemoveBlock(string manifest)
    {
        var lines = manifest.Replace("\r\n", "\n").Split('\n').ToList();
        int start = lines.FindIndex(l => l.Trim() == BlockStart);
        if (start < 0) return manifest;
        int end = lines.FindIndex(start, l => l.Trim() == BlockEnd);
        if (end < 0) return manifest;   // damaged block: left for the user to repair
        if (start > 0 && lines[start - 1].Trim().Length == 0) start--;
        lines.RemoveRange(start, end - start + 1);
        return string.Join("\n", lines);
    }

    // Each client: the sounds near its player, nearest first, at most MaxLocalActive at once.
    public static string Client(Open77SoundSet set, string project)
    {
        var local = set.Emitters.Where(e => !e.Settings.Synced).ToArray();
        int budget = Math.Clamp(Open77Audio.HandlesPerResource - set.Synced, 0, MaxLocalActive);
        var lua = new StringBuilder();
        lua.Append($"{Marker} from the world project \"{Escape(project)}\": its custom sounds, started near each player.\n");
        lua.Append("-- Rewritten by every export: edit the sounds in the Studio, not here.\n");
        lua.Append("local SOUNDS = {\n");
        foreach (var e in local)
        {
            lua.Append($"    {{ name = {Quote(e.Name)}, file = {Quote(e.PublishedPath)}, x = {N(e.Position.X)}, y = {N(e.Position.Y)}, z = {N(e.Position.Z)}, volume = {N(e.Settings.Volume)}, min = {N(e.Settings.MinDistance)}, max = {N(e.MaxDistance)}");
            lua.Append(e.Settings.Playback == SoundPlayback.Loop ? ", loop = true },\n" : $", pause = {{ {N(e.Settings.IntervalMin)}, {N(e.Settings.IntervalMax)} }}, duration = {N((float)e.Duration)} }},\n");
        }
        lua.Append("}\n");
        lua.Append($"local MAX_ACTIVE = {budget}\n");
        lua.Append("""
            local active = {}   -- index in SOUNDS -> { id = handle, nextAt = ms }

            local function stop(i)
                local a = active[i]
                if a and a.id then DestroySound(a.id) end
                active[i] = nil
            end

            local function start(i, s, a, now)
                if s.loop then
                    if a.id then return end
                    local id, why = Play3DSound(s.file, { x = s.x, y = s.y, z = s.z }, { loop = true, volume = s.volume, minDistance = s.min, maxDistance = s.max })
                    if id then a.id = id elseif not a.warned then a.warned = true; print(("[ncwe sounds] %s: %s"):format(s.name, tostring(why))) end
                elseif now >= a.nextAt then
                    -- A finished local clip is restarted by PlaySound; a new handle only the first time.
                    if a.id then PlaySound(a.id)
                    else
                        local id, why = Play3DSound(s.file, { x = s.x, y = s.y, z = s.z }, { volume = s.volume, minDistance = s.min, maxDistance = s.max })
                        if id then a.id = id elseif not a.warned then a.warned = true; print(("[ncwe sounds] %s: %s"):format(s.name, tostring(why))) end
                    end
                    a.nextAt = now + math.floor((s.duration + s.pause[1] + math.random() * (s.pause[2] - s.pause[1])) * 1000)
                end
            end

            CreateThread(function()
                while true do
                    local state = Open77.character.state()
                    local here = state and state.position
                    if here and MAX_ACTIVE > 0 then
                        -- Started within 5 m of their reach, stopped 15 m beyond it.
                        local near = {}
                        for i, s in ipairs(SOUNDS) do
                            local dx, dy, dz = s.x - here.x, s.y - here.y, s.z - here.z
                            local d = math.sqrt(dx * dx + dy * dy + dz * dz)
                            if d <= s.max + (active[i] and 15 or 5) then near[#near + 1] = { i = i, d = d } end
                        end
                        table.sort(near, function(a, b) return a.d < b.d end)
                        local keep = {}
                        for k = 1, math.min(#near, MAX_ACTIVE) do keep[near[k].i] = true end
                        for i in pairs(active) do if not keep[i] then stop(i) end end
                        local now = GetGameTimer()
                        for i in pairs(keep) do
                            local s = SOUNDS[i]
                            if not active[i] then
                                -- Repeated sounds start after a random part of their pause, so neighbours do not chime together.
                                active[i] = { nextAt = s.loop and 0 or now + math.floor(math.random() * s.pause[2] * 1000) }
                            end
                            start(i, s, active[i], now)
                        end
                    end
                    Wait(500)
                end
            end)

            """);
        return lua.ToString();
    }

    // The server: synced loops, one timeline for every player in routing bucket 0 (late joiners included).
    public static string Server(Open77SoundSet set, string project)
    {
        var lua = new StringBuilder();
        lua.Append($"{Marker} from the world project \"{Escape(project)}\": its synced custom sounds.\n");
        lua.Append("-- Rewritten by every export: edit the sounds in the Studio, not here.\n");
        lua.Append("local SOUNDS = {\n");
        foreach (var e in set.Emitters.Where(e => e.Settings.Synced))
            lua.Append($"    {{ name = {Quote(e.Name)}, file = {Quote(e.PublishedPath)}, x = {N(e.Position.X)}, y = {N(e.Position.Y)}, z = {N(e.Position.Z)}, volume = {N(e.Settings.Volume)}, min = {N(e.Settings.MinDistance)}, max = {N(e.MaxDistance)}, duration = {N((float)Math.Min(e.Duration, Open77Audio.MaxDuration))} }},\n");
        lua.Append("}\n");
        lua.Append("""
            for _, s in ipairs(SOUNDS) do
                local id, why = Play3DSound(s.file, { x = s.x, y = s.y, z = s.z }, { loop = true, duration = s.duration, volume = s.volume, minDistance = s.min, maxDistance = s.max })
                if not id then print(("[ncwe sounds] %s: %s"):format(s.name, tostring(why))) end
            end

            """);
        return lua.ToString();
    }

    private static string N(float value) => value.ToString("0.###", CultureInfo.InvariantCulture);
    private static string Quote(string text) => "\"" + Escape(text) + "\"";
    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ").Replace("\r", " ");
}
