using System.IO.Compression;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace NCWE.Export;

public sealed record Open77ResourceReport(string ResourceDirectory, string ResourceName, string Version, string RequiredModId,
    string PackagePath, string PackageSha256, long PackageBytes, IReadOnlyList<string> PackageEntries, bool ManifestCreated, IReadOnlyList<string> Notes)
{
    // Custom sounds placed in the world, and the sound files copied into the resource.
    public int Sounds { get; init; }
    public IReadOnlyList<string> SoundFiles { get; init; } = [];
}

// An NCWE export as an Open77 world resource: `open77.lua` declares the package with
// `preload_mod`, so the dedicated server promotes it to the required mod `<resource>-assets`
// and the launcher installs it before the game starts (Open77 wiki: server-resources.md,
// "Pre-boot REDengine assets"). The package must be inert and game-root relative
// (archive/pc/mod/...), and ArchiveXL comes from the `archivexl` loader resource.
public static partial class Open77ResourceExporter
{
    // Open77 limits (ResourceManifestParser, ResourcePreloadModResolver, ModRootPolicy).
    public const long MaximumPackageBytes = 256L * 1024 * 1024;
    private const string PackageRoot = "archive/pc/mod/";
    private static readonly HashSet<string> Executable = new(StringComparer.OrdinalIgnoreCase)
        { ".dll", ".exe", ".asi", ".so", ".dylib", ".sys", ".com", ".scr", ".reds", ".lua", ".bat", ".cmd", ".ps1", ".vbs", ".js" };
    // Fixed entry times: zipping the same files always gives the same bytes.
    private static readonly DateTimeOffset EntryTime = new(2026, 1, 1, 0, 0, 0, TimeSpan.Zero);
    private const string Marker = "-- Generated by NCWE Studio";

    [GeneratedRegex("^[a-z0-9][a-z0-9_-]{0,63}$", RegexOptions.CultureInvariant)] private static partial Regex ResourceNamePattern();
    [GeneratedRegex(@"^(?<indent>\s*)(?<key>resource|version|preload_mod|dependency|server_script|client_script|shared_script|files)\b(?<rest>.*)$", RegexOptions.CultureInvariant)] private static partial Regex DirectiveLine();
    [GeneratedRegex(@"(['""])(?<v>.*?)\1", RegexOptions.CultureInvariant)] private static partial Regex Quoted();

    public static bool IsResourceName(string name) => ResourceNamePattern().IsMatch(name);

    public static Open77ResourceReport Write(ExportResult export, string resourceDirectory, Open77SoundSet? sounds = null) =>
        Write(export, resourceDirectory, sounds ?? Open77SoundSet.Empty, export.Manifest.ProjectName, export.Manifest.ProjectId);

    // A project whose only changes are custom sounds: a resource without a world package (a package
    // an earlier export preloaded is removed with its manifest lines).
    public static Open77ResourceReport WriteSoundsOnly(string resourceDirectory, Open77SoundSet sounds, string projectName, Guid projectId) =>
        Write(null, resourceDirectory, sounds, projectName, projectId);

    private static Open77ResourceReport Write(ExportResult? export, string resourceDirectory, Open77SoundSet sounds, string project, Guid projectId)
    {
        Open77Sounds.Validate(sounds);
        if (export is null && sounds.IsEmpty) throw new InvalidDataException("The project has no exportable changes.");
        string directory = Path.GetFullPath(resourceDirectory).TrimEnd(Path.DirectorySeparatorChar);
        string name = Path.GetFileName(directory);
        if (!IsResourceName(name))
            throw new InvalidDataException($"An Open77 resource folder must be named in lowercase letters, digits, '_' or '-' (the folder name is the resource name): \"{name}\". Create a folder such as \"ncwe_{Slug(project)}\".");

        // Package: the mod files only, under their game-relative root.
        var files = export?.Manifest.Files.Where(f => f.RelativePath.Replace('\\', '/').StartsWith(PackageRoot, StringComparison.OrdinalIgnoreCase)).ToArray() ?? [];
        if (export is not null && files.Length == 0) throw new InvalidDataException("The export has no archive/pc/mod files to package.");
        foreach (var file in files)
            if (Executable.Contains(Path.GetExtension(file.RelativePath)))
                throw new InvalidDataException($"{file.RelativePath} would make the package executable; Open77 preloads accept inert data only.");

        string manifestPath = Path.Combine(directory, "open77.lua");
        bool created = !File.Exists(manifestPath);
        string? previous = created ? null : File.ReadAllText(manifestPath);
        string? earlierPackage = ExistingPreload(previous);
        string packageRelative = earlierPackage ?? $"dist/{name.Replace('_', '-')}.zip";
        string packagePath = Path.GetFullPath(Path.Combine(directory, packageRelative.Replace('/', Path.DirectorySeparatorChar)));
        if (!packagePath.StartsWith(directory + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase))
            throw new InvalidDataException($"The manifest's preload_mod \"{packageRelative}\" points outside the resource.");
        string sha = "";
        long size = 0;
        var entries = new List<string>();
        if (export is not null)
        {
            WritePackage(export, files, packagePath, entries);
            using (var stream = File.OpenRead(packagePath)) sha = Convert.ToHexStringLower(SHA256.HashData(stream));
            size = new FileInfo(packagePath).Length;
        }
        else if (earlierPackage is not null && File.Exists(packagePath)) File.Delete(packagePath);

        // Custom sounds: their files under sounds/ and the generated scripts that play them.
        WriteSounds(directory, sounds, PreviousSounds(directory), project);

        // Manifest: written whole the first time; afterwards only the lines NCWE owns change
        // (resource, version bump, preload_mod, the ArchiveXL dependency, the sound block).
        string version = NextVersion(previous);
        string? dependency = export is null ? null : $"archivexl >={export.Manifest.TargetArchiveXlVersion}";
        string? package = export is null ? null : packageRelative;
        string manifest = previous is null ? NewManifest(name, version, dependency, package, project)
            : UpdateManifest(Open77Sounds.RemoveBlock(previous), name, version, dependency, package, earlierPackage);
        bool hasScript = Regex.IsMatch(manifest, @"(?m)^\s*(server_script|client_script|shared_script|files)\b");
        bool addsMain = !hasScript && sounds.IsEmpty;
        if (addsMain) manifest = manifest.TrimEnd() + "\nserver_script \"server/main.lua\"\n";
        if (!sounds.IsEmpty) manifest = manifest.TrimEnd() + "\n\n" + Open77Sounds.ManifestBlock(sounds);
        // The placeholder script, only for a line NCWE wrote (an existing manifest's scripts are left alone).
        string scriptPath = Path.Combine(directory, "server", "main.lua");
        if ((addsMain || created) && manifest.Contains("\"server/main.lua\"", StringComparison.Ordinal) && !File.Exists(scriptPath))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(scriptPath)!);
            File.WriteAllText(scriptPath, $"-- Generated by NCWE Studio: the world itself is the preloaded package; nothing runs here.\nAddEventHandler(\"onResourceStart\", function(resource)\n    if resource ~= GetCurrentResourceName() then return end\n    print(\"[{name}] NCWE world \\\"{LuaEscape(project)}\\\" is installed by the launcher before the game starts.\")\nend)\n");
        }
        WriteAtomic(manifestPath, manifest);

        var notes = ServerNotes(directory, name).ToList();
        if (export is null) notes.Add("Only custom sounds: nothing is preloaded (no required mod); the sounds are ordinary resource files.");
        if (!sounds.IsEmpty)
            notes.Add($"{sounds.Emitters.Count} custom sound{(sounds.Emitters.Count == 1 ? "" : "s")} ({sounds.Files.Count} file{(sounds.Files.Count == 1 ? "" : "s")} in sounds/): server and clients need Open77 op77.62 or newer (package audio)."
                + (sounds.Synced > 0 ? $" {sounds.Synced} synced on the server." : ""));
        var record = new
        {
            generator = "NCWE Studio", project, projectId, exportedUtc = export?.Manifest.CreatedUtc ?? DateTimeOffset.UtcNow,
            game = export?.Manifest.GameProductVersion, archiveXl = export?.Manifest.TargetArchiveXlVersion, resource = name, version, requiredMod = export is null ? null : name + "-assets",
            package, sha256 = sha, bytes = size, entries,
            changes = export is null ? null : new { export.Manifest.Transformed, export.Manifest.Deleted, export.Manifest.Added, export.Manifest.Roads, export.Manifest.Elements },
            sounds = sounds.Files.Select(f => f.PublishedPath).ToArray(), soundEmitters = sounds.Emitters.Count, syncedSounds = sounds.Synced,
            sourceExport = export?.Directory
        };
        WriteAtomic(Path.Combine(directory, "ncwe-export.json"), JsonSerializer.Serialize(record, new JsonSerializerOptions { WriteIndented = true }));
        return new(directory, name, version, export is null ? "" : name + "-assets", export is null ? "" : packagePath, sha, size, entries, created, notes)
            { Sounds = sounds.Emitters.Count, SoundFiles = sounds.Files.Select(f => f.PublishedPath).ToArray() };
    }

    // The zip of the mod files, written next to its final name then moved over it.
    private static void WritePackage(ExportResult export, PackageFile[] files, string packagePath, List<string> entries)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(packagePath)!);
        string temporary = packagePath + ".tmp-" + Guid.NewGuid().ToString("N")[..8];
        try
        {
            using (var stream = new FileStream(temporary, FileMode.CreateNew))
            using (var zip = new ZipArchive(stream, ZipArchiveMode.Create))
            {
                foreach (var file in files.OrderBy(f => f.RelativePath, StringComparer.Ordinal))
                {
                    string source = Path.Combine(export.Directory, file.RelativePath.Replace('/', Path.DirectorySeparatorChar));
                    if (!File.Exists(source) || !string.Equals(ModExporter.HashFile(source), file.Sha256, StringComparison.OrdinalIgnoreCase))
                        throw new InvalidDataException($"{file.RelativePath} changed since the export; export again.");
                    string entryName = file.RelativePath.Replace('\\', '/');
                    var entry = zip.CreateEntry(entryName, CompressionLevel.Optimal);
                    entry.LastWriteTime = EntryTime;
                    using var input = File.OpenRead(source);
                    using var output = entry.Open();
                    input.CopyTo(output);
                    entries.Add(entryName);
                }
            }
            long bytes = new FileInfo(temporary).Length;
            if (bytes > MaximumPackageBytes) throw new InvalidDataException($"The package is {bytes:N0} bytes; Open77 preloads are limited to {MaximumPackageBytes:N0}.");
            File.Move(temporary, packagePath, overwrite: true);
        }
        finally { if (File.Exists(temporary)) File.Delete(temporary); }
    }

    // Copies the sound files (unchanged ones are left alone), removes those an earlier export wrote
    // and this one no longer uses, and writes or removes the generated scripts.
    private static void WriteSounds(string directory, Open77SoundSet sounds, IReadOnlyCollection<string> previous, string project)
    {
        foreach (var file in sounds.Files)
        {
            string target = Inside(directory, file.PublishedPath);
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            if (File.Exists(target) && new FileInfo(target).Length == file.Bytes && ModExporter.HashFile(target) == ModExporter.HashFile(file.SourcePath)) continue;
            string temporary = target + ".tmp-" + Guid.NewGuid().ToString("N")[..8];
            File.Copy(file.SourcePath, temporary);
            File.Move(temporary, target, overwrite: true);
        }
        var kept = sounds.Files.Select(f => f.PublishedPath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        foreach (var old in previous.Where(p => !kept.Contains(p) && p.StartsWith("sounds/", StringComparison.Ordinal) && !p.Contains("..")))
        {
            string path = Inside(directory, old);
            if (File.Exists(path)) File.Delete(path);
        }
        WriteOrRemove(Inside(directory, Open77Sounds.ClientScript), sounds.Emitters.Any(e => !e.Settings.Synced) ? Open77Sounds.Client(sounds, project) : null);
        WriteOrRemove(Inside(directory, Open77Sounds.ServerScript), sounds.Synced > 0 ? Open77Sounds.Server(sounds, project) : null);
    }

    private static void WriteOrRemove(string path, string? content)
    {
        if (content is not null) { Directory.CreateDirectory(Path.GetDirectoryName(path)!); WriteAtomic(path, content); return; }
        // Only a script NCWE generated is removed.
        if (File.Exists(path) && File.ReadLines(path).FirstOrDefault()?.StartsWith(Open77Sounds.Marker, StringComparison.Ordinal) == true) File.Delete(path);
    }

    // The sound files the previous export of this resource wrote (ncwe-export.json).
    private static IReadOnlyCollection<string> PreviousSounds(string directory)
    {
        try
        {
            string record = Path.Combine(directory, "ncwe-export.json");
            if (!File.Exists(record)) return [];
            using var json = JsonDocument.Parse(File.ReadAllText(record));
            return json.RootElement.TryGetProperty("sounds", out var list) && list.ValueKind == JsonValueKind.Array
                ? list.EnumerateArray().Where(e => e.ValueKind == JsonValueKind.String).Select(e => e.GetString()!).ToArray() : [];
        }
        catch (Exception ex) when (ex is IOException or JsonException or UnauthorizedAccessException) { return []; }
    }

    private static string Inside(string directory, string relative)
    {
        string path = Path.GetFullPath(Path.Combine(directory, relative.Replace('/', Path.DirectorySeparatorChar)));
        if (!path.StartsWith(directory + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) throw new InvalidDataException($"{relative} points outside the resource.");
        return path;
    }

    private static string NewManifest(string name, string version, string? dependency, string? package, string project) =>
        package is null
            ? $"{Marker} from the world project \"{LuaEscape(project)}\": its custom sounds (no world changes to preload).\n" +
              $"resource \"{name}\"\nversion \"{version}\"\nauto_start true\n"
            : $"{Marker} from the world project \"{LuaEscape(project)}\".\n" +
              "-- The package is preloaded as the required mod \"" + name + "-assets\": the launcher installs it\n" +
              "-- before Cyberpunk starts. Changing it needs a dedicated-server restart, then a fresh game launch.\n" +
              $"resource \"{name}\"\nversion \"{version}\"\nauto_start true\n\ndependency \"{dependency}\"\npreload_mod \"{package}\"\n\nserver_script \"server/main.lua\"\n";

    // Without a package (only custom sounds), NCWE's preload_mod line and the ArchiveXL dependency go.
    private static string UpdateManifest(string source, string name, string version, string? dependency, string? package, string? earlierPackage)
    {
        var lines = source.Replace("\r\n", "\n").Split('\n').ToList();
        bool resource = false, versionSet = false, preload = false, xl = false;
        for (int i = 0; i < lines.Count; i++)
        {
            var match = DirectiveLine().Match(lines[i]);
            if (!match.Success) continue;
            string indent = match.Groups["indent"].Value, value = Quoted().Match(match.Groups["rest"].Value) is { Success: true } q ? q.Groups["v"].Value : "";
            switch (match.Groups["key"].Value)
            {
                case "resource": lines[i] = $"{indent}resource \"{name}\""; resource = true; break;
                case "version": lines[i] = $"{indent}version \"{version}\""; versionSet = true; break;
                case "preload_mod" when package is null && string.Equals(value.Replace('\\', '/'), earlierPackage, StringComparison.OrdinalIgnoreCase): lines.RemoveAt(i--); break;
                case "preload_mod" when package is not null && !preload: lines[i] = $"{indent}preload_mod \"{package}\""; preload = true; break;
                case "dependency" when value.StartsWith("archivexl", StringComparison.OrdinalIgnoreCase):
                    if (dependency is null) lines.RemoveAt(i--); else { lines[i] = $"{indent}dependency \"{dependency}\""; xl = true; }
                    break;
            }
        }
        if (!resource) lines.Insert(0, $"resource \"{name}\"");
        if (!versionSet) lines.Insert(lines.FindIndex(l => l.TrimStart().StartsWith("resource", StringComparison.Ordinal)) + 1, $"version \"{version}\"");
        int at = lines.FindLastIndex(l => DirectiveLine().IsMatch(l)) + 1;
        if (!xl && dependency is not null) lines.Insert(at++, $"dependency \"{dependency}\"");
        if (!preload && package is not null) lines.Insert(at, $"preload_mod \"{package}\"");
        return string.Join("\n", lines).TrimEnd() + "\n";
    }

    // The package path the manifest already declares (kept so the resource stays stable).
    private static string? ExistingPreload(string? manifest)
    {
        if (manifest is null) return null;
        var match = Regex.Match(manifest, @"(?m)^\s*preload_mod\s*\(?\s*(['""])(?<v>[^'""]+\.zip)\1");
        return match.Success && !match.Groups["v"].Value.Contains('*') && !match.Groups["v"].Value.Contains("..") ? match.Groups["v"].Value.Replace('\\', '/') : null;
    }

    // Each export raises the patch number ("1.0.3" → "1.0.4"); new resources start at 1.0.0.
    private static string NextVersion(string? manifest)
    {
        if (manifest is null) return "1.0.0";
        var match = Regex.Match(manifest, @"(?m)^\s*version\s*\(?\s*(['""])(?<major>\d+)\.(?<minor>\d+)\.(?<patch>\d+)\1");
        return match.Success ? $"{match.Groups["major"].Value}.{match.Groups["minor"].Value}.{int.Parse(match.Groups["patch"].Value) + 1}" : "1.0.0";
    }

    // Looks for the server configurations above the resource: does one load it, with required mods on?
    private static IEnumerable<string> ServerNotes(string resourceDirectory, string name)
    {
        var folder = new DirectoryInfo(resourceDirectory).Parent;
        while (folder is not null && !string.Equals(folder.Name, "resources", StringComparison.OrdinalIgnoreCase)) folder = folder.Parent;
        if (folder?.Parent is not { } server) { yield return "No Open77 server folder (…\\resources\\…) found above this resource: add it to a server's resources and its resources.load list."; yield break; }
        var configurations = server.EnumerateFiles("server*.jsonc").Concat(server.EnumerateFiles("server*.json")).ToArray();
        if (configurations.Length == 0) { yield return $"No server configuration in {server.FullName}."; yield break; }
        bool loader = Directory.EnumerateDirectories(folder.FullName, "archivexl", new EnumerationOptions { RecurseSubdirectories = true, MaxRecursionDepth = 3, IgnoreInaccessible = true })
            .Any(d => File.Exists(Path.Combine(d, "open77.lua")));
        if (!loader) yield return "The server has no \"archivexl\" loader resource (resources/assets/loaders/archivexl): the world needs ArchiveXL.";
        foreach (var file in configurations)
        {
            string text;
            try { text = File.ReadAllText(file.FullName); } catch (IOException) { continue; }
            bool loads = Regex.IsMatch(text, $"\"{Regex.Escape(name)}\"") || Regex.IsMatch(text, "\"load\"\\s*:\\s*\\[\\s*\"\\*\"");
            bool required = Regex.IsMatch(text, "\"requiredMods\"\\s*:\\s*\\{[^}]*?\"enabled\"\\s*:\\s*true", RegexOptions.Singleline);
            bool unsecured = Regex.IsMatch(text, "\"requiredMods\"\\s*:\\s*\\{[^}]*?\"unsecured\"\\s*:\\s*true", RegexOptions.Singleline);
            yield return $"{file.Name}: " + (loads ? "loads it" : $"does not list \"{name}\" in resources.load") + ", requiredMods " + (required ? "enabled" : "disabled (required to preload)")
                + (required && loader && !unsecured ? ", not unsecured (the ArchiveXL loader is executable)" : "") + ".";
        }
    }

    private static string Slug(string text)
    {
        var builder = new StringBuilder();
        foreach (char c in text.ToLowerInvariant()) builder.Append(c is >= 'a' and <= 'z' or >= '0' and <= '9' ? c : '_');
        string slug = Regex.Replace(builder.ToString(), "_+", "_").Trim('_');
        return slug.Length == 0 ? "world" : slug[..Math.Min(slug.Length, 40)];
    }

    private static string LuaEscape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", " ");

    private static void WriteAtomic(string path, string content)
    {
        string temporary = path + ".tmp-" + Guid.NewGuid().ToString("N")[..8];
        File.WriteAllText(temporary, content, new UTF8Encoding(false));
        File.Move(temporary, path, overwrite: true);
    }
}
